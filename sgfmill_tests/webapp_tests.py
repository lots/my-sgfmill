"""Run the web app's tests as part of the library's testsuite.

The web app in :file:`WebApp/` is a JavaScript port of this library, so it has
its own tests, written for Node. They are run from here when Node is available,
and skipped (not failed) when it is not, so that the library's testsuite still
runs anywhere.

The port itself is checked against the Python library: WebApp/tests/
generate_expected.py asks sgfmill what each fixture means, and the Node tests
compare the JavaScript answers with those.
"""

import os
import shutil
import subprocess
import sys
import unittest

from . import sgfmill_test_support


def make_tests(suite):
    suite.addTests(sgfmill_test_support.make_simple_tests(globals()))


_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_WEBAPP = os.path.join(_ROOT, "WebApp")


def _node():
    """The Node executable, or None."""
    return shutil.which("node")


def _run_node(script, timeout=300):
    """Run one of the web app's test scripts, returning (ok, output)."""
    result = subprocess.run(
        [_node(), os.path.join("tests", script)],
        cwd=_WEBAPP, capture_output=True, timeout=timeout,
    )
    output = (result.stdout + result.stderr).decode("utf-8", "replace")
    return result.returncode == 0, output


def test_engine_matches_the_python_library(tc):
    """The JavaScript engine must agree with sgfmill about every fixture.

    WebApp/tests/expected.json is generated by the Python library, so this is a
    genuine comparison and not the port checking itself.
    """
    if _node() is None:
        tc.skipTest("node is not installed")
    if not os.path.exists(os.path.join(_WEBAPP, "tests", "expected.json")):
        tc.skipTest("WebApp/tests/expected.json has not been generated; run "
                    "python WebApp/tests/generate_expected.py")
    ok, output = _run_node("engine_test.mjs")
    tc.assertTrue(ok, "engine tests failed:\n%s" % output[-4000:])
    tc.assertIn("0 failed", output)

def test_web_app_interface(tc):
    """The page must load and work, driven through jsdom."""
    if _node() is None:
        tc.skipTest("node is not installed")
    if not os.path.isdir(os.path.join(_WEBAPP, "node_modules", "jsdom")):
        tc.skipTest("jsdom is not installed; run 'npm install' in WebApp/")
    ok, output = _run_node("ui_test.mjs")
    tc.assertTrue(ok, "interface tests failed:\n%s" % output[-4000:])
    tc.assertIn("0 failed", output)

def test_web_app_has_no_runtime_dependencies(tc):
    """The web app must stay deployable as plain files.

    The library's most useful property is that it needs nothing, and the web
    app should not quietly give that up: no imports from a CDN, no npm packages
    at run time. jsdom is a development dependency, used only by the tests.
    """
    import re
    offenders = []
    for name in sorted(os.listdir(os.path.join(_WEBAPP, "js"))):
        if not name.endswith(".js"):
            continue
        with open(os.path.join(_WEBAPP, "js", name), encoding="utf-8") as f:
            source = f.read()
        for match in re.finditer(r"""^\s*import\b[^;]*?from\s+["']([^"']+)["']""",
                                 source, re.MULTILINE):
            target = match.group(1)
            if not target.startswith("./") and not target.startswith("../"):
                offenders.append("%s imports %s" % (name, target))
        for match in re.finditer(r"""https?://[^\s"')]+""", source):
            offenders.append("%s mentions %s" % (name, match.group(0)))
    tc.assertEqual(offenders, [], "the web app must not need anything at run time")

def test_web_app_files_are_present(tc):
    """The pieces a static host needs must all be in WebApp/."""
    required = ["index.html", "styles.css", "js/app.js", "js/sgf.js",
                "js/board.js", "js/moves.js", "js/properties.js",
                "js/tools.js", "README.md", "serve.py", "run_web_app.cmd"]
    for name in required:
        path = os.path.join(_WEBAPP, name)
        tc.assertTrue(os.path.exists(path), "missing %s" % name)
        tc.assertGreater(os.path.getsize(path), 0, "%s is empty" % name)

def test_launcher_is_a_batch_file_that_will_parse(tc):
    """run_web_app.cmd must stay ASCII with CRLF line endings.

    cmd.exe's parser is fragile with anything else, and a stray non-ASCII
    character is invisible until the launcher fails on someone's machine.
    """
    path = os.path.join(_WEBAPP, "run_web_app.cmd")
    if not os.path.exists(path):
        tc.skipTest("the Windows launcher is not present")
    with open(path, "rb") as f:
        data = f.read()
    tc.assertEqual([b for b in data if b > 127], [],
                   "run_web_app.cmd contains non-ASCII bytes")
    tc.assertFalse(data.startswith(b"\xef\xbb\xbf"), "it has a byte order mark")
    bare_lf = data.count(b"\n") - data.count(b"\r\n")
    tc.assertEqual(bare_lf, 0, "it has LF line endings rather than CRLF")

def test_serve_script_uses_only_the_standard_library(tc):
    """The launcher's server must not need anything installed."""
    import ast
    path = os.path.join(_WEBAPP, "serve.py")
    if not os.path.exists(path):
        tc.skipTest("serve.py is not present")
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    imported = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module.split(".")[0])
    allowed = set(sys.stdlib_module_names)
    tc.assertEqual(sorted(imported - allowed), [],
                   "serve.py imports something that is not in the standard "
                   "library")
